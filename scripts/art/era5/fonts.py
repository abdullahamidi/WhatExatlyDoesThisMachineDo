def text_mask(s, font, gap=1):
    rows = len(next(iter(font.values()))); w = sum(len(font[c][0]) + gap for c in s) - gap
    m = [[0] * w for _ in range(rows)]; x = 0
    for c in s:
        g = font[c]
        for j in range(rows):
            for i, ch in enumerate(g[j]):
                if ch == '#': m[j][x + i] = 1
        x += len(g[0]) + gap
    return m
